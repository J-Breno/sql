SELECT
	CLIENTE,
	QUANTIDADE,
	VENDEDOR,
	PRODUTO,
	MOVIMENTO
FROM
	VENDAS_ANALITICAS
WHERE CLIENTE IN(1876, 1422, 2249) AND QUANTIDADE > 0 AND VENDEDOR IN(4, 16) AND PRODUTO IN (34726, 34304, 34394, 34593)
ORDER BY MOVIMENTO ASC

SELECT
	MOVIMENTO,
	ENTIDADE,
	TITULO,
	VALOR
FROM
	TITULOS_RECEBER
WHERE 
	MOVIMENTO >= '01/01/2020'
	AND ENTIDADE IN(1874, 2308, 1520) 
	AND TITULO LIKE '%/1%'
	AND (VALOR BETWEEN 150.00 AND 255.23 
	OR VALOR BETWEEN 425.57 AND 550.12)
SELECT
	CONCAT(ESPECIE_FISCAL, ' ',  DOCUMENTO_NUMERO) AS DOCUMENTO,
	VENDEDOR,
	MOVIMENTO,
	PRODUTO,
	VENDA_BRUTA / QUANTIDADE AS VALOR_UNITARIO
FROM
	VENDAS_ANALITICAS
WHERE MOVIMENTO > '01/06/2020'
ORDER BY MOVIMENTO ASC


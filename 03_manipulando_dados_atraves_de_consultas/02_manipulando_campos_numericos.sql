-- CEILING - ARREDONDA VALORES PARA BAIXO
-- FLOOR - ARREDONDA VALORES PARA CIMA
-- ROUND - ARREDONDA VALORES COM CRITÉRIOS MATEMÁTICOS
-- ABS - RETORNA VALORES ABSOLUTO

SELECT 
	TOP 100
	PRODUTO,
	QUANTIDADE,
	VENDA_BRUTA,
	CEILING(VENDA_BRUTA) AS FUNCAO_CEILING,
	FLOOR(VENDA_BRUTA) AS FUNCAO_FLOOR,
	ROUND(VENDA_BRUTA, 0) AS FUNCAO_ROUND,
	ABS(VENDA_BRUTA) AS FUNCAO_ABS
FROM 
	VENDAS_ANALITICAS

SELECT TOP 100
	COALESCE(VENDEDOR, '0'),
	PRODUTO,
	QUANTIDADE,
	ROUND(VENDA_BRUTA / QUANTIDADE, 2) AS VALOR_UNITARIO,
	VENDA_BRUTA
FROM
	VENDAS_ANALITICAS
WHERE VENDEDOR IS NULL
ORDER BY VENDA_BRUTA / QUANTIDADE DESC

SELECT TOP 100
	COALESCE(VENDEDOR, '0'),
	PRODUTO,
	QUANTIDADE,
	ROUND(VENDA_BRUTA / QUANTIDADE, 2) AS VALOR_UNITARIO,
	VENDA_BRUTA
FROM
	VENDAS_ANALITICAS
WHERE VENDEDOR IS NOT NULL
ORDER BY VALOR_UNITARIO DESC
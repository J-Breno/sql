-- NULL = auxente de informação
-- ISNULL = FUNÇÃO PARA TRATAR VALORES NULOS
-- COALESCE = FUNÇÃO PADRÃO ANSI PARA TRATAR VALOR NULOS

SELECT CIDADE, ESTADO, ISNULL(COMPLEMENTO, 'SEM COMPLEMENTO') AS FUNCAO_ISNULL, COALESCE(COMPLEMENTO, 'SEM COMPLEMENTO') AS FUNCAO_COALESCE
FROM ENDERECOS

SELECT CIDADE, ESTADO, MUNICIPIO FROM ENDERECOS WHERE COALESCE(MUNICIPIO, -1) <> 1832

SELECT CIDADE, ESTADO, MUNICIPIO FROM ENDERECOS WHERE MUNICIPIO IS NULL
SELECT CIDADE, ESTADO, MUNICIPIO FROM ENDERECOS WHERE MUNICIPIO IS NOT NULL

SELECT CIDADE, ESTADO, NULLIF(NULLIF(COMPLEMENTO, ''), 'CNPJ: 00.029.372/0007-36') AS FUNCAO_NULLIF FROM ENDERECOS WHERE NULLIF(NULLIF(COMPLEMENTO, ''), 'CNPJ: 00.029.372/0007-36') IS NULL
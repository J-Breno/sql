MERGE D_CLIENTE D
USING PBS_PROCFIT_ST.DBO.VW_D_CLIENTES O ON D.COD_CLIENTE = O.COD_CLIENTE


--QUANDO COINCIDIR
WHEN MATCHED THEN UPDATE
SET NOME           = O.NOME
  , NOME_FANTASIA  = O.NOME_FANTASIA
  , CLASSSIFICACAO = O.CLASSIFICACAO_CLIENTE
  , CIDADE         = O.CIDADE
  , ESTADO         = O.ESTADO
  , UF             = O.UF

--QUANDO NÃO COINCIDIR NO DESTINO
WHEN NOT MATCHED BY TARGET THEN INSERT
( COD_CLIENTE
, NOME
, NOME_FANTASIA
, CLASSSIFICACAO
, CIDADE
, ESTADO
, UF )

VALUES
(
  O.COD_CLIENTE
, O.NOME
, O.NOME_FANTASIA
, O.CLASSIFICACAO_CLIENTE
, O.CIDADE
, O.ESTADO
, O.UF
);

